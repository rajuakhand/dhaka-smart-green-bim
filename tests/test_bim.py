FIXTURE_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fixtures")
SAMPLE_M = os.path.join(FIXTURE_DIR, "sample_m.ifc")
SAMPLE_MM = os.path.join(FIXTURE_DIR, "sample_mm.ifc")


def ensure_fixtures():
    """Generate the sample IFC files if they are missing."""
    if os.path.exists(SAMPLE_M) and os.path.exists(SAMPLE_MM):
        return
    import sys
    sys.path.insert(0, FIXTURE_DIR)
    import make_sample_ifc
    make_sample_ifc.build_ifc(SAMPLE_M, use_millimetres=False)
    make_sample_ifc.build_ifc(SAMPLE_MM, use_millimetres=True)


