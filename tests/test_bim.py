@requires_ifc
class TestRoomTypeInference:
    def test_known_types(self):
        from src.modules.bim.converter import infer_room_type
        cases = {
            "Living Room": "Residential",
            "Bedroom 2": "Residential",
            "Kitchen": "Residential",
            "Office 101": "Office",
            "Meeting Room": "Office",
            "Classroom A": "Classroom",
            "Storage": "Storage",
            "Laboratory": "Laboratory",
            "Retail Shop": "Retail",
            "Ward 3": "Hospital",
            "Assembly Hall": "Assembly",
        }
        for name, expected in cases.items():
            rt, matched = infer_room_type(name)
            assert rt == expected, f"{name} -> {rt}, expected {expected}"
            assert matched is True

    def test_unknown_falls_back_to_other(self):
        from src.modules.bim.converter import infer_room_type
        rt, matched = infer_room_type("XYZ-9876")
        assert rt == "Other"
        assert matched is False

    def test_empty_name(self):
        from src.modules.bim.converter import infer_room_type
        rt, matched = infer_room_type(None)
        assert rt == "Other"
        assert matched is False

    def test_case_insensitive(self):
        from src.modules.bim.converter import infer_room_type
        assert infer_room_type("BEDROOM")[0] == "Residential"
        assert infer_room_type("bedroom")[0] == "Residential"

    def test_long_name_used(self):
        from src.modules.bim.converter import infer_room_type
        rt, _ = infer_room_type("SP-01", long_name="Kitchen")
        assert rt == "Residential"


