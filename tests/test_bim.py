@requires_ifc
class TestUnitScaling:
    """The critical IFC unit-scaling tests.

    The same building exported in metres and in millimetres must produce
    identical metric values. Getting this wrong is the classic "room is 1000x
    too small" bug.
    """

    def setup_method(self):
        ensure_fixtures()

    def test_millimetre_file_detected(self):
        from src.modules.bim.parser import parse_ifc
        model = parse_ifc(SAMPLE_MM)
        assert model.length_unit == "MILLI METRE"
        assert model.length_scale == pytest.approx(0.001)

    def test_metre_file_scale_is_one(self):
        from src.modules.bim.parser import parse_ifc
        model = parse_ifc(SAMPLE_M)
        assert model.length_unit == "METRE"
        assert model.length_scale == pytest.approx(1.0)

    def test_both_files_give_identical_areas(self):
        from src.modules.bim.parser import parse_ifc
        m = parse_ifc(SAMPLE_M)
        mm = parse_ifc(SAMPLE_MM)
        assert m.total_floor_area_m2 == pytest.approx(mm.total_floor_area_m2, abs=1e-6)
        assert m.total_envelope_area_m2 == pytest.approx(mm.total_envelope_area_m2, abs=1e-6)
        assert m.total_window_area_m2 == pytest.approx(mm.total_window_area_m2, abs=1e-6)

    def test_both_files_give_identical_walls(self):
        from src.modules.bim.parser import parse_ifc
        m = parse_ifc(SAMPLE_M)
        mm = parse_ifc(SAMPLE_MM)
        for a, b in zip(m.walls, mm.walls):
            assert a.x_dim_m == pytest.approx(b.x_dim_m, abs=1e-6)
            assert a.y_dim_m == pytest.approx(b.y_dim_m, abs=1e-6)
            assert a.z_dim_m == pytest.approx(b.z_dim_m, abs=1e-6)
            assert a.volume_m3 == pytest.approx(b.volume_m3, abs=1e-6)

    def test_conversion_note_emitted(self):
        from src.modules.bim.parser import model_summary, parse_ifc
        summary = model_summary(parse_ifc(SAMPLE_MM))
        assert any("converted" in w.lower() for w in summary["warnings"])

    def test_metre_file_has_no_conversion_warning(self):
        from src.modules.bim.parser import model_summary, parse_ifc
        summary = model_summary(parse_ifc(SAMPLE_M))
        assert not any("converted from" in w.lower() for w in summary["warnings"])


