@requires_ifc
class TestBimToAnalysisIntegration:
    """Prove that a BIM room can flow into the real calculation engines."""

    def setup_method(self):
        ensure_fixtures()

    def test_bim_room_feeds_room_analyzer(self):
        from src.models.schemas import RoomCreate, RoomType
        from src.modules.bim.converter import convert_to_analysis_model
        from src.modules.bim.parser import parse_ifc
        from src.modules.room_analyzer import analyze_room

        r = convert_to_analysis_model(parse_ifc(SAMPLE_M))
        room_dict = r["rooms"][0]
        room = RoomCreate(
            name=room_dict["name"],
            room_type=RoomType(room_dict["room_type"]),
            length_m=room_dict["length_m"],
            width_m=room_dict["width_m"],
            height_m=room_dict["height_m"],
            window_area_m2=room_dict["window_area_m2"],
            openable_window_area_m2=room_dict["openable_window_area_m2"],
            occupants=4,
        )
        result = analyze_room(room)
        assert result["floor_area_m2"] == pytest.approx(20.0, abs=1e-6)
        assert result["volume_m3"] == pytest.approx(60.0, abs=1e-6)

    def test_bim_envelope_drives_density(self):
        from src.modules.bim.converter import convert_to_analysis_model
        from src.modules.bim.parser import parse_ifc
        from src.modules.density import calculate_density

        r = convert_to_analysis_model(parse_ifc(SAMPLE_M))
        d = calculate_density(
            total_floor_area_m2=r["total_floor_area_m2"],
            plot_area_m2=r["footprint_m2"] * 4,
            footprint_m2=r["footprint_m2"],
            total_occupants=4,
        )
        assert d["far"] is not None
        assert d["far"] > 0

    def test_bim_glazing_ratio_drives_daylight_screening(self):
        """The IFC-derived glazing ratio must be usable by the daylight module."""
        from src.modules.bim.converter import convert_to_analysis_model
        from src.modules.bim.parser import parse_ifc
        from src.modules.daylight_factor import average_daylight_factor

        r = convert_to_analysis_model(parse_ifc(SAMPLE_M))
        room = r["rooms"][0]
        df = average_daylight_factor(
            window_area_m2=room["window_area_m2"],
            window_width_m=1.5,
            window_height_m=1.2,
            room_length_m=room["length_m"],
            room_width_m=room["width_m"],
            room_height_m=room["height_m"],
            glazing_type="Clear",
        )
        assert df["daylight_factor_percent"] >= 0.0
        assert df["method"]

    def test_bim_room_can_run_phase2(self):
        from src.models.schemas import BuildingCreate, RoomCreate, BuildingType, RoomType
        from src.modules.bim.converter import convert_to_analysis_model
        from src.modules.bim.parser import parse_ifc
        from src.services.phase2_service import run_phase2_analysis

        r = convert_to_analysis_model(parse_ifc(SAMPLE_M))
        room_dict = r["rooms"][0]
        rooms = [RoomCreate(
            name=room_dict["name"],
            room_type=RoomType(room_dict["room_type"]),
            length_m=room_dict["length_m"],
            width_m=room_dict["width_m"],
            height_m=room_dict["height_m"],
            window_area_m2=room_dict["window_area_m2"],
            openable_window_area_m2=room_dict["openable_window_area_m2"],
            occupants=4,
        )]
        building = BuildingCreate(
            name="BIM Imported",
            building_type=BuildingType.RESIDENTIAL,
            num_floors=1,
            floor_to_floor_height_m=3.0,
            orientation_deg=180.0,
            plot_area_m2=r["footprint_m2"] * 4,
            building_footprint_m2=r["footprint_m2"],
        )
        result = run_phase2_analysis(building, rooms)
        assert result["modules"]["daylight_factor"]["rooms"]
        assert result["modules"]["climate"]["dataset"]["dataset_id"]